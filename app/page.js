"use client";
import { useEffect, useRef, useState } from "react";
const MODEL_ID = "Imagers/imager-1";
const MODEL_URL = "https://huggingface.co/Imagers/Imager-1";
const API_URL = "https://validio-production.up.railway.app/predict";
const VISITOR_STORAGE_KEY = "imager_visitor_id";
function getVisitorId() {
  if (typeof window === "undefined") return "";
  let id = window.localStorage.getItem(VISITOR_STORAGE_KEY);
  if (!id) {
    id = window.crypto?.randomUUID?.() || `${Date.now()}-${Math.random().toString(36).slice(2)}`;
    window.localStorage.setItem(VISITOR_STORAGE_KEY, id);
  }
  return id;
}

export default function Home() {
  const [file,setFile]=useState(null), [preview,setPreview]=useState("");
  const [status,setStatus]=useState("ready"), [result,setResult]=useState(null), [error,setError]=useState(""), [limitReached,setLimitReached]=useState(false);
  const inputRef=useRef(null);
  useEffect(()=>{if(!file){setPreview("");return;}const u=URL.createObjectURL(file);setPreview(u);return()=>URL.revokeObjectURL(u);},[file]);
  function choose(f){if(!f)return;if(!f.type.startsWith("image/")){setError("Please choose a valid image file.");return;}if(f.size>10*1024*1024){setError("Please choose an image smaller than 10 MB.");return;}setFile(f);setResult(null);setError("");setLimitReached(false);}
  async function analyze(){
    if(!file)return;setStatus("analyzing");setError("");setLimitReached(false);setResult(null);
    try{
      const body=new FormData();body.append("file",file);
      body.append("visitor_id", getVisitorId());
      const response=await fetch(API_URL,{method:"POST",body});
      const raw=await response.text();let data;try{data=JSON.parse(raw)}catch{data={detail:raw}};
      if(!response.ok) {
        if (response.status === 429) {
          setLimitReached(true);
          setError("You’ve used all your detection requests for today. Please come back tomorrow.");
          setStatus("ready");
          return;
        }
        throw new Error(`API error ${response.status}: ${data.detail||data.message||raw}`);
      }
      const label=String(data.label||data.prediction||data.result||data.class||"Analysis complete");
      const conf=Number(data.confidence??data.score??data.probability);
      const isAI=/ai|generated|fake|synthetic/i.test(label);
      setResult({label,isAI,confidence:Number.isFinite(conf)?(conf<=1?conf*100:conf).toFixed(2):null,raw:data});
      setStatus("ready");
    }catch(e){
      setStatus("ready");
      setError(e instanceof TypeError?"Could not connect to the Railway API. Check that the service is online and allows CORS for this website.":(e.message||"Analysis failed. Try another image."));
    }
  }
  const busy=status==="analyzing";
  return <main>
    <header className="topbar"><a className="brand" href="#top"><img src="/logo.png" alt="Imager logo"/><span>imager</span></a></header>
    <section className="hero" id="top">
      <p className="eyebrow">IMAGERS · OPEN MODEL</p><h1>Try Imager 1</h1><p className="subtitle">Detect AI images with AI.</p>
      <p className="intro">Upload an image to estimate whether it was generated by artificial intelligence or captured in the real world.</p>
      <div className="upload-card">
        <input ref={inputRef} className="hidden-input" type="file" accept="image/*" onChange={e=>choose(e.target.files?.[0])}/>
        <button className={`dropzone ${file?"has-file":""}`} type="button" onClick={()=>inputRef.current?.click()}>
          {preview?<img className="preview" src={preview} alt="Selected image preview"/>:<><span className="upload-icon">↑</span><strong>Choose an image</strong><span className="muted">Click to browse files · JPG, PNG, WEBP · max 10 MB</span></>}
        </button>
        {file&&<p className="filename">{file.name}</p>}
        <button className="analyze-button" disabled={!file||busy} onClick={analyze}>{busy?"Analyzing image…":"Analyze"}</button>
        {error&&<p className={limitReached?"error limit-error":"error"} role="alert">{error}</p>}
        {result&&<div className="result" aria-live="polite"><div className="result-heading"><span className={`result-dot ${result.isAI?"ai":"real"}`}/><h2>{result.label}</h2></div>{result.confidence!==null&&<><p className="confidence">{result.confidence}<span>%</span></p><p className="muted">Confidence returned by the API</p></>}<pre style={{whiteSpace:"pre-wrap",overflowWrap:"anywhere",fontSize:12,textAlign:"left"}}>{JSON.stringify(result.raw,null,2)}</pre><p className="disclaimer">This is a model prediction, not proof of an image’s origin. Results may be wrong, especially on edited, compressed, or unfamiliar images.</p></div>}
      </div>
    </section>
    <section className="about"><div className="about-inner">
      <p className="eyebrow">ABOUT THE MODEL</p><h2>Meet Imager-1</h2>
      <p>Imager-1 is an image-classification model from Imagers, built to distinguish AI-generated images from real-world photography. This demo sends images to the configured Railway API for analysis.</p>
      <p>The model is available on Hugging Face. Visit its model page to explore its files, model information, and usage details.</p>
      <a className="model-link" href={MODEL_URL} target="_blank" rel="noreferrer">Explore Imager-1 on Hugging Face <span>↗</span></a>
      <div className="future-note"><h3>More powerful models are on the way</h3><p>We’re interested in developing and releasing more capable models in the future. If you’re interested in these models, follow the project on Hugging Face for updates, new releases, and opportunities to explore what comes next.</p></div>
      <p className="model-meta">Model ID: <code>{MODEL_ID}</code></p>
    </div></section>
    <footer><a href={MODEL_URL} target="_blank" rel="noreferrer">Imagers on Hugging Face</a><span>Built for exploration · Results are estimates</span></footer>
  </main>;
}
